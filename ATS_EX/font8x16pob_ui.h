inline uint8_t pobIndex(uint8_t c)
{
    if (c >= 'A' && c <= 'Z')
        return (uint8_t)(15 + (c - 'A'));
    if (c >= 'a' && c <= 'z')
        return (uint8_t)(15 + (c - 'a'));
    if (c >= '0' && c <= '9')
        return (uint8_t)(5 + (c - '0'));
    if (c == ' ')
        return 0;
    if (c == '+')
        return 1;
    if (c == '-')
        return 2;
    if (c == '.')
        return 3;
    if (c == '/')
        return 4;
    return 0;
}
